-- B2-lite: worker profile + skills (PRD WP-1, WP-3).
-- Not yet: work proofs, medical notes, completed_gigs (each comes with its own later migration).

-- The fixed skill list workers pick from. Admins will manage it later; for now it is seeded below.
CREATE TABLE skills (
    id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name  VARCHAR(50) NOT NULL UNIQUE
);

-- One row per worker, created the first time they save their profile.
-- user_id is both the primary key and the link to users: a user has at most one worker profile.
CREATE TABLE worker_profiles (
    user_id           UUID PRIMARY KEY REFERENCES users (id),
    photo_url         VARCHAR(500),
    description       VARCHAR(1000),
    languages         TEXT[]       NOT NULL DEFAULT '{}',
    experience_years  INTEGER      NOT NULL DEFAULT 0 CHECK (experience_years BETWEEN 0 AND 60),
    experience_level  VARCHAR(15)  NOT NULL DEFAULT 'BEGINNER'
                      CHECK (experience_level IN ('BEGINNER', 'INTERMEDIATE', 'EXPERIENCED')),
    -- Kept up to date by the app on every save: photo + at least 1 skill + at least 1 language.
    profile_complete  BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- Join table: which worker has which skill. The composite key stops the same skill being added twice.
CREATE TABLE worker_skills (
    user_id   UUID   NOT NULL REFERENCES worker_profiles (user_id),
    skill_id  BIGINT NOT NULL REFERENCES skills (id),
    PRIMARY KEY (user_id, skill_id)
);

-- The primary key already covers lookups by user_id; this one serves "workers with skill X" (gig matching).
CREATE INDEX idx_worker_skills_skill_id ON worker_skills (skill_id);

