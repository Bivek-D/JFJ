-- Cached aggregates on the user, kept in step inside the same transaction that changes them (10.2).
-- Ratings are split by role: as a worker and as a provider. Average = sum / count, worked out on read.
ALTER TABLE users
    ADD COLUMN rating_sum             INTEGER NOT NULL DEFAULT 0 CHECK (rating_sum >= 0),
    ADD COLUMN rating_count           INTEGER NOT NULL DEFAULT 0 CHECK (rating_count >= 0),
    ADD COLUMN provider_rating_sum    INTEGER NOT NULL DEFAULT 0 CHECK (provider_rating_sum >= 0),
    ADD COLUMN provider_rating_count  INTEGER NOT NULL DEFAULT 0 CHECK (provider_rating_count >= 0),
    -- Always equals SUM(xp_events.points) for this user; never below 0.
    ADD COLUMN total_xp               INTEGER NOT NULL DEFAULT 0 CHECK (total_xp >= 0),
    ADD COLUMN level                  INTEGER NOT NULL DEFAULT 1 REFERENCES level_config (level);

-- Optional: the lowest earned level a worker needs to apply (PRD 5.7). NULL = anyone.
ALTER TABLE gigs ADD COLUMN min_level INTEGER REFERENCES level_config (level);

CREATE TABLE reviews (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    assignment_id  UUID        NOT NULL REFERENCES assignments (id),
    reviewer_id    UUID        NOT NULL REFERENCES users (id),
    reviewee_id    UUID        NOT NULL REFERENCES users (id),
    direction      VARCHAR(20) NOT NULL CHECK (direction IN ('PROVIDER_TO_WORKER', 'WORKER_TO_PROVIDER')),
    rating         INTEGER     NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment        VARCHAR(500),
    edit_count     INTEGER     NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- DONE-4: one review per reviewer per assignment.
    UNIQUE (assignment_id, reviewer_id)
);

-- "Reviews this user received", newest first.
CREATE INDEX idx_reviews_reviewee ON reviews (reviewee_id, created_at DESC);

-- Append-only log: rows are only ever inserted. It is the source of truth for XP; users.total_xp is a cache.
CREATE TABLE xp_events (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     UUID        NOT NULL REFERENCES users (id),
    event_type  VARCHAR(30) NOT NULL CHECK (event_type IN
                ('GIG_COMPLETED', 'GIG_COMPLETED_PROVIDER', 'PROFILE_COMPLETE', 'RATING_RECEIVED', 'RATING_ADJUST')),
    points      INTEGER     NOT NULL,
    -- What the award is for: assignment, gig, user or review id (PRD 5.7 table).
    ref_id      UUID        NOT NULL,
    -- 0 for one-off awards; for RATING_ADJUST, the review's edit_count.
    version     INTEGER     NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    -- Idempotency: the same award can never be written twice, even if the code runs twice.
    UNIQUE (user_id, event_type, ref_id, version)
);
