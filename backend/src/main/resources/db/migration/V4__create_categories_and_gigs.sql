CREATE TABLE gigs (
    id                   UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    provider_id          UUID          NOT NULL REFERENCES users (id),
    category_id          BIGINT        NOT NULL REFERENCES categories (id),
    title                VARCHAR(100)  NOT NULL,
    description          VARCHAR(2000) NOT NULL,
    pay_type             VARCHAR(10)   NOT NULL CHECK (pay_type IN ('FIXED', 'HOURLY', 'DAILY')),
    -- Exact decimal, 2 places: 690.34 stays 690.34 (a float could store 690.3399999...).
    pay_amount           NUMERIC(10,2) NOT NULL CHECK (pay_amount > 0),
    workers_needed       INTEGER       NOT NULL CHECK (workers_needed BETWEEN 1 AND 50),
    -- Optional: the lowest self-declared experience a worker needs (NULL = anyone).
    min_experience       VARCHAR(15)   CHECK (min_experience IN ('BEGINNER', 'INTERMEDIATE', 'EXPERIENCED')),
    start_date           DATE          NOT NULL,
    duration_text        VARCHAR(100)  NOT NULL,
    apply_deadline       DATE,
    address_line         VARCHAR(255)  NOT NULL,
    locality             VARCHAR(100)  NOT NULL,
    city                 VARCHAR(100)  NOT NULL,
    -- Exact pin: shown only to the owner (and hired workers, B4).
    location             geometry(Point, 4326) NOT NULL,
    -- Exact pin moved 300-500 m in a random direction, once. Search, map and distance use only this.
    public_location      geometry(Point, 4326) NOT NULL,
    location_edit_count  INTEGER       NOT NULL DEFAULT 0 CHECK (location_edit_count BETWEEN 0 AND 3),
    status               VARCHAR(12)   NOT NULL DEFAULT 'DRAFT'
                         CHECK (status IN ('DRAFT', 'OPEN', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED', 'EXPIRED')),
    -- Keyword search (Day 7). Postgres keeps it up to date by itself; 'english' matches "cleaning" to "clean".
    search_vector        tsvector GENERATED ALWAYS AS
                         (to_tsvector('english', title || ' ' || description)) STORED,
    created_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CHECK (apply_deadline IS NULL OR apply_deadline <= start_date)
);

-- Map area search (bounding box) works on the geometry index.
CREATE INDEX idx_gigs_public_location ON gigs USING GIST (public_location);
-- Radius search in metres (ST_DWithin on geography) needs an index on the same expression.
CREATE INDEX idx_gigs_public_location_geog ON gigs USING GIST ((public_location::geography));
CREATE INDEX idx_gigs_search_vector ON gigs USING GIN (search_vector);
-- "Newest open gigs" and "my gigs".
CREATE INDEX idx_gigs_status_created ON gigs (status, created_at DESC);
CREATE INDEX idx_gigs_category ON gigs (category_id);
CREATE INDEX idx_gigs_provider ON gigs (provider_id);

-- Skills a gig asks for. Deleting a draft gig removes its rows here too.
CREATE TABLE gig_skills (
    gig_id    UUID   NOT NULL REFERENCES gigs (id) ON DELETE CASCADE,
    skill_id  BIGINT NOT NULL REFERENCES skills (id),
    PRIMARY KEY (gig_id, skill_id)
);

CREATE INDEX idx_gig_skills_skill_id ON gig_skills (skill_id);
