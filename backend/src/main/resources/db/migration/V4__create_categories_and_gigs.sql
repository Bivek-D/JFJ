-- B3-lite: categories and gigs (PRD 5.3, 6.3).
-- Not yet: gig_photos (Cloudinary), min_level (B5, with levels), cancel_reason/completed_at (B4).

-- What kind of gig it is (one per gig). Skills say what the worker must be able to do (many per gig).
CREATE TABLE categories (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(50) NOT NULL UNIQUE,
    sort_order  INTEGER     NOT NULL,
    active      BOOLEAN     NOT NULL DEFAULT TRUE
);

